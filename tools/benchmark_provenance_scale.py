#!/usr/bin/env python3
"""Measure monolithic PROV-JSON behavior for a synthetic HPC campaign.

This benchmark deliberately builds through the ``prov`` object model instead
of repeatedly calling ``Manager.add_activity``. It measures one complete
document construction, serialization, load, and SQLite replacement. Repeated
high-level authoring currently rewrites the growing document after every call
and therefore has worse cumulative behavior than the single-rewrite result.
"""

from __future__ import annotations

import argparse
import gzip
import json
import sqlite3
import tempfile
import tracemalloc
import uuid
from dataclasses import asdict, dataclass
from pathlib import Path
from statistics import median
from time import perf_counter

from prov.model import PROV, ProvDocument

from hpc_campaign.prov_mapping import HPC, CampaignProvIds
from hpc_campaign.prov_store import ProvStore, canonical_prov_json, create_provenance_tables


@dataclass(frozen=True)
class Scenario:
    """Scientific products generated by the representative campaign."""

    simulations: int
    variables_per_simulation: int
    reductions_per_variable: int
    qois_per_variable: int
    visualizations_per_simulation: int = 1

    @property
    def products(self) -> int:
        return self.simulations * (
            self.variables_per_simulation * (1 + self.reductions_per_variable + self.qois_per_variable)
            + self.visualizations_per_simulation
        )

    @property
    def expected_records(self) -> int:
        # Four Agents and one simulation Plan are shared. Each simulation adds
        # a Dataset, Activity, and Association. Source variables add an Entity
        # and Generation. Every derived/visual product adds Entity, Activity,
        # Usage, Generation, Derivation, and Association.
        shared = 5
        per_simulation = (
            3
            + self.variables_per_simulation * (2 + 6 * (self.reductions_per_variable + self.qois_per_variable))
            + 6 * self.visualizations_per_simulation
        )
        return shared + self.simulations * per_simulation


@dataclass(frozen=True)
class Measurement:  # pylint: disable=too-many-instance-attributes
    """Measured costs for one fully materialized scenario."""

    scenario: Scenario
    products: int
    records: int
    canonical_bytes: int
    gzip_bytes: int
    sqlite_bytes: int
    build_seconds: float
    serialize_seconds: float
    deserialize_seconds: float
    sqlite_insert_seconds: float
    sqlite_rewrite_seconds: float
    sqlite_load_seconds: float
    build_peak_bytes: int
    serialize_peak_bytes: int
    deserialize_peak_bytes: int


def _stable_uuid(campaign_id: uuid.UUID, name: str) -> uuid.UUID:
    return uuid.uuid5(campaign_id, name)


def _logical_variable_attributes(  # pylint: disable=too-many-arguments,too-many-positional-arguments
    variable_id: uuid.UUID,
    dataset,
    dataset_name: str,
    variable: str,
    definition: str,
    location: str,
):
    return [
        (PROV["type"], HPC["LogicalVariable"]),
        (HPC["logicalVariableId"], str(variable_id)),
        (HPC["dataset"], dataset),
        (HPC["datasetName"], dataset_name),
        (HPC["variable"], variable),
        (HPC["variableDefinition"], definition),
        (PROV["location"], location),
    ]


def _add_processing_activity(  # pylint: disable=too-many-arguments,too-many-positional-arguments
    document: ProvDocument,
    identifiers: CampaignProvIds,
    campaign_id: uuid.UUID,
    name: str,
    activity_type,
    source,
    output,
    metadata,
    agent,
) -> None:
    """Add the six records made by a representative derived product."""

    activity_id = _stable_uuid(campaign_id, f"activity:{name}")
    activity = identifiers.activity(activity_id)
    source_usage = identifiers.usage(activity_id, "source")
    generation = identifiers.generation(activity_id, "result")
    attributes = [(PROV["type"], activity_type)]
    if metadata is not None:
        attributes.append(
            (HPC["metadata"], json.dumps(metadata, sort_keys=True, separators=(",", ":"), allow_nan=False))
        )
    document.activity(activity, other_attributes=attributes)
    document.used(
        activity,
        source,
        identifier=source_usage,
        other_attributes=[(PROV["role"], HPC["source"])],
    )
    document.wasGeneratedBy(
        output,
        activity,
        identifier=generation,
        other_attributes=[(PROV["role"], HPC["result"])],
    )
    document.wasDerivedFrom(
        output,
        source,
        activity,
        generation,
        source_usage,
        identifier=identifiers.derivation(activity_id, "result", "source"),
    )
    document.wasAssociatedWith(activity, agent)


def _add_shared_records(document: ProvDocument, identifiers: CampaignProvIds, campaign_id: uuid.UUID):
    agents = {}
    for name in ("simulation", "reduction", "qoi", "visualization"):
        reference = identifiers.agent(_stable_uuid(campaign_id, f"agent:{name}"))
        document.agent(
            reference,
            [(PROV["type"], PROV["SoftwareAgent"]), (PROV["label"], name)],
        )
        agents[name] = reference

    simulation_plan = identifiers.plan(_stable_uuid(campaign_id, "plan:simulation"))
    document.entity(
        simulation_plan,
        [(PROV["type"], PROV["Plan"]), (PROV["label"], "simulation configuration")],
    )
    return agents, {"simulation": simulation_plan}


def build_document(  # pylint: disable=too-many-locals
    scenario: Scenario,
    campaign_id: uuid.UUID,
) -> ProvDocument:
    """Build the sampled graph without exercising cumulative ACA rewrites."""

    identifiers = CampaignProvIds(campaign_id)
    document = ProvDocument()
    document.add_namespace(HPC)
    document.add_namespace(identifiers.namespace)
    agents, plans = _add_shared_records(document, identifiers, campaign_id)

    for simulation_index in range(scenario.simulations):
        simulation_name = f"simulation-{simulation_index:04d}"
        simulation_id = _stable_uuid(campaign_id, f"simulation:{simulation_index}")
        simulation = identifiers.activity(simulation_id)
        dataset_id = _stable_uuid(campaign_id, f"dataset:{simulation_index}")
        dataset = identifiers.dataset(dataset_id)
        dataset_name = f"output-{simulation_index:04d}"
        location = f"data/{simulation_name}/output.bp"
        document.entity(
            dataset,
            [
                (PROV["type"], HPC["Dataset"]),
                (PROV["label"], dataset_name),
                (HPC["datasetUuid"], str(dataset_id)),
                (HPC["format"], "ADIOS"),
                (PROV["location"], location),
            ],
        )
        document.activity(
            simulation,
            other_attributes=[
                (PROV["type"], HPC["Simulation"]),
                (PROV["label"], simulation_name),
            ],
        )
        document.wasAssociatedWith(simulation, agents["simulation"], plans["simulation"])

        first_source = None
        for variable_index in range(scenario.variables_per_simulation):
            source_name = f"s{simulation_index}:v{variable_index}:source"
            source_id = _stable_uuid(campaign_id, source_name)
            source = identifiers.variable(source_id)
            if first_source is None:
                first_source = source
            definition = f"variable_{variable_index:03d}"
            document.entity(
                source,
                _logical_variable_attributes(
                    source_id,
                    dataset,
                    dataset_name,
                    definition,
                    definition,
                    location,
                ),
            )
            document.wasGeneratedBy(
                source,
                simulation,
                identifier=identifiers.generation(simulation_id, definition),
                other_attributes=[(PROV["role"], HPC[definition])],
            )

            for action, count, activity_type, metadata, agent in (
                (
                    "reduction",
                    scenario.reductions_per_variable,
                    HPC["Reduction"],
                    {"method": "reduction"},
                    agents["reduction"],
                ),
                (
                    "qoi",
                    scenario.qois_per_variable,
                    HPC["QuantityOfInterest"],
                    {"operation": "quantity_of_interest"},
                    agents["qoi"],
                ),
            ):
                for product_index in range(count):
                    product_name = f"s{simulation_index}:v{variable_index}:{action}:{product_index}"
                    product_id = _stable_uuid(campaign_id, product_name)
                    product = identifiers.variable(product_id)
                    document.entity(
                        product,
                        _logical_variable_attributes(
                            product_id,
                            dataset,
                            dataset_name,
                            f"{definition}_{action}_{product_index}",
                            definition,
                            location,
                        ),
                    )
                    _add_processing_activity(
                        document,
                        identifiers,
                        campaign_id,
                        product_name,
                        activity_type,
                        source,
                        product,
                        metadata,
                        agent,
                    )

        if first_source is None:
            continue
        for visualization_index in range(scenario.visualizations_per_simulation):
            product_name = f"s{simulation_index}:visualization:{visualization_index}"
            product_id = _stable_uuid(campaign_id, product_name)
            product = identifiers.dataset(product_id)
            document.entity(
                product,
                [
                    (PROV["type"], HPC["Dataset"]),
                    (PROV["type"], HPC["Image"]),
                    (HPC["datasetUuid"], str(product_id)),
                    (HPC["format"], "IMAGE"),
                    (PROV["label"], f"image_{visualization_index}"),
                    (PROV["location"], f"data/{simulation_name}/image_{visualization_index}.png"),
                ],
            )
            _add_processing_activity(
                document,
                identifiers,
                campaign_id,
                product_name,
                HPC["Visualization"],
                first_source,
                product,
                {"representation": "visualization"},
                agents["visualization"],
            )
    return document


def _median_seconds(operation, repeats: int):
    durations = []
    result = None
    for _ in range(repeats):
        started = perf_counter()
        result = operation()
        durations.append(perf_counter() - started)
    return median(durations), result


def measure(scenario: Scenario, repeats: int) -> Measurement:  # pylint: disable=too-many-locals
    """Measure one materialized graph and one complete SQLite rewrite."""

    campaign_id = uuid.UUID("8c13a4ce-3662-43cd-a03b-2fdfd53bd65e")
    tracemalloc.start()
    started = perf_counter()
    document = build_document(scenario, campaign_id)
    build_seconds = perf_counter() - started
    _, build_peak = tracemalloc.get_traced_memory()
    tracemalloc.stop()

    records = len(list(document.get_records()))
    if records != scenario.expected_records:
        raise RuntimeError(f"record-count model is stale: expected {scenario.expected_records}, built {records}")

    tracemalloc.start()
    serialize_seconds, canonical = _median_seconds(
        lambda: canonical_prov_json(document),
        repeats,
    )
    _, serialize_peak = tracemalloc.get_traced_memory()
    tracemalloc.stop()
    assert isinstance(canonical, str)

    tracemalloc.start()
    deserialize_seconds, loaded = _median_seconds(
        lambda: ProvDocument.deserialize(content=canonical, format="json"),
        repeats,
    )
    _, deserialize_peak = tracemalloc.get_traced_memory()
    tracemalloc.stop()
    assert isinstance(loaded, ProvDocument)

    with tempfile.TemporaryDirectory(prefix="hpc-campaign-prov-benchmark-") as temporary:
        database_path = Path(temporary) / "benchmark.aca"
        connection = sqlite3.connect(database_path)
        connection.row_factory = sqlite3.Row
        create_provenance_tables(connection.cursor(), campaign_id)
        connection.commit()
        store = ProvStore(connection)

        started = perf_counter()
        info = store.add_document(document, name="benchmark", active=False)
        insert_seconds = perf_counter() - started
        rewrite_seconds, info = _median_seconds(
            lambda: store.replace_document(
                info.document_id,
                document,
                expected_sha256=info.sha256,
            ),
            repeats,
        )
        load_seconds, stored_document = _median_seconds(
            lambda: store.document(info.document_id),
            repeats,
        )
        assert isinstance(stored_document, ProvDocument)
        connection.close()
        sqlite_bytes = database_path.stat().st_size

    return Measurement(
        scenario=scenario,
        products=scenario.products,
        records=records,
        canonical_bytes=len(canonical.encode("utf-8")),
        gzip_bytes=len(gzip.compress(canonical.encode("utf-8"), compresslevel=6)),
        sqlite_bytes=sqlite_bytes,
        build_seconds=build_seconds,
        serialize_seconds=serialize_seconds,
        deserialize_seconds=deserialize_seconds,
        sqlite_insert_seconds=insert_seconds,
        sqlite_rewrite_seconds=rewrite_seconds,
        sqlite_load_seconds=load_seconds,
        build_peak_bytes=build_peak,
        serialize_peak_bytes=serialize_peak,
        deserialize_peak_bytes=deserialize_peak,
    )


def _positive(value: str) -> int:
    parsed = int(value)
    if parsed <= 0:
        raise argparse.ArgumentTypeError("value must be positive")
    return parsed


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--simulations", type=_positive, default=10)
    parser.add_argument("--variables", type=_positive, default=20)
    parser.add_argument("--reductions", type=_positive, default=2)
    parser.add_argument("--qois", type=_positive, default=3)
    parser.add_argument("--visualizations", type=int, default=1)
    parser.add_argument("--repeats", type=_positive, default=3)
    args = parser.parse_args()
    if args.visualizations < 0:
        parser.error("--visualizations must not be negative")

    scenario = Scenario(
        simulations=args.simulations,
        variables_per_simulation=args.variables,
        reductions_per_variable=args.reductions,
        qois_per_variable=args.qois,
        visualizations_per_simulation=args.visualizations,
    )
    result = measure(scenario, args.repeats)
    print(json.dumps(asdict(result), indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
